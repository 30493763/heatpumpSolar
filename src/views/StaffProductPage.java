    private void lstStaffProductPage_SelectCategoryValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstStaffProductPage_SelectCategoryValueChanged
        // TODO add your handling code here:

        String productCategorySelected = lstStaffProductPage_SelectCategory.getSelectedValue();
        System.out.println("clickdd: " + productCategorySelected);

        //creating new list Model before manupulating the model the form!!!
        DefaultListModel lstProductsModel = new DefaultListModel();

        for(Product product : allProducts){
            System.out.println("in for loop, product.getProductType(): " + product.getProductType());

            if(product.getProductType().equals(productCategorySelected)){
                lstProductsModel.addElement(product);
            }
        }
        lstStaffProductPage_SelectProduct.setModel(lstProductsModel);
    }//GEN-LAST:event_lstStaffProductPage_SelectCategoryValueChanged

